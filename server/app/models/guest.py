from sqlalchemy import (
    CheckConstraint,
    Computed,
    ForeignKey,
    Identity,
    Index,
    String,
    Text,
    UniqueConstraint,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base, TimestampMixin

# Digits only, so "+46 70-123 45 67" and "46701234567" match.
PHONE_DIGITS_SQL: str = "regexp_replace(phone, '[^0-9]', '', 'g')"


class Guest(TimestampMixin, Base):
    """A guest profile at one property.

    Email and phone are contact details: only returned with guest.view_contact, never
    logged. Emails are stored trimmed and lower-case (the check below), so lookups are
    case-insensitive in effect.
    """

    __tablename__ = "guests"
    __table_args__ = (
        CheckConstraint(
            "email IS NULL OR (email = lower(btrim(email)) AND email <> '')",
            name="email_normalised",
        ),
        # Target of reservations' (guest_id, property_id) foreign key.
        UniqueConstraint("id", "property_id", name="uq_guests_id_property_id"),
        # Lists sorted by name; exact lookups by email and phone (find an existing guest).
        Index(
            "ix_guests_property_id_last_name_first_name", "property_id", "last_name", "first_name"
        ),
        Index("ix_guests_property_id_email", "property_id", "email"),
        Index("ix_guests_property_id_phone_digits", "property_id", "phone_digits"),
        # Substring search over name, email and phone digits (ILIKE '%term%').
        Index(
            "ix_guests_search_text_trgm",
            "search_text",
            postgresql_using="gin",
            postgresql_ops={"search_text": "gin_trgm_ops"},
        ),
    )

    id: Mapped[int] = mapped_column(Identity(), primary_key=True)
    property_id: Mapped[int] = mapped_column(ForeignKey("properties.id", ondelete="RESTRICT"))
    first_name: Mapped[str] = mapped_column(String(100))
    last_name: Mapped[str] = mapped_column(String(100))
    email: Mapped[str | None] = mapped_column(String(320))
    phone: Mapped[str | None] = mapped_column(String(50))
    notes: Mapped[str | None] = mapped_column(Text)
    # Generated by the database; never set them.
    phone_digits: Mapped[str | None] = mapped_column(
        String(50), Computed(PHONE_DIGITS_SQL, persisted=True)
    )
    search_text: Mapped[str] = mapped_column(
        Text,
        Computed(
            "lower(first_name || ' ' || last_name || ' ' || coalesce(email, '') || ' ' || "
            f"coalesce({PHONE_DIGITS_SQL}, ''))",
            persisted=True,
        ),
    )

    def __repr__(self) -> str:
        # No contact details: reprs end up in logs and tracebacks.
        return f"<Guest {self.id}>"
